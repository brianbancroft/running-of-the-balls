import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const lock = JSON.parse(readFileSync(path.join(root, "package-lock.json"), "utf8"));
const manifest = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const direct = new Set([
  ...Object.keys(manifest.dependencies ?? {}),
  ...Object.keys(manifest.devDependencies ?? {}),
]);

const DIRECT_ALLOW = new Set([
  "MIT",
  "Apache-2.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "ISC",
  "0BSD",
  "MIT-0",
  "BSD-2-Clause-Patent",
]);

const TRANSITIVE_ALLOW = new Set([
  ...DIRECT_ALLOW,
  "CC0-1.0",
  "Unlicense",
  "BlueOak-1.0.0",
  "Python-2.0",
  "MPL-2.0",
  "LGPL-2.1-only",
  "LGPL-2.1-or-later",
  "LGPL-3.0-only",
  "LGPL-3.0-or-later",
  "Artistic-2.0",
]);

const COMMON = new Map([
  ["mit", "MIT"],
  ["mit license", "MIT"],
  ["apache-2.0", "Apache-2.0"],
  ["apache 2.0", "Apache-2.0"],
  ["apache license 2.0", "Apache-2.0"],
  ["apache license, version 2.0", "Apache-2.0"],
  ["bsd-2-clause", "BSD-2-Clause"],
  ["bsd-3-clause", "BSD-3-Clause"],
  ["isc", "ISC"],
  ["0bsd", "0BSD"],
  ["cc0-1.0", "CC0-1.0"],
  ["unlicense", "Unlicense"],
  ["mpl-2.0", "MPL-2.0"],
]);

function licenseOf(entry, packageDir) {
  const fromLock = normalizeLicense(entry.license);
  if (fromLock) return fromLock;
  const packageJsonPath = path.join(packageDir, "package.json");
  if (!existsSync(packageJsonPath)) return "";
  const pkg = JSON.parse(readFileSync(packageJsonPath, "utf8"));
  return normalizeLicense(pkg.license ?? pkg.licenses);
}

function normalizeLicense(value) {
  if (!value) return "";
  if (Array.isArray(value)) {
    return value.map((item) => normalizeLicense(item)).filter(Boolean).join(" OR ");
  }
  if (typeof value === "object") return normalizeLicense(value.type ?? "");
  return String(value).replace(/\s+/g, " ").trim();
}

function canonical(token) {
  const cleaned = token.trim().replace(/^\(+|\)+$/g, "").trim();
  return COMMON.get(cleaned.toLowerCase()) ?? cleaned;
}

function splitTop(expression, word) {
  const parts = [];
  let current = "";
  let depth = 0;
  const pattern = new RegExp(`\\s+${word}\\s+`, "i");
  for (let index = 0; index < expression.length; index += 1) {
    const char = expression[index];
    if (char === "(") depth += 1;
    if (char === ")") depth -= 1;
    if (depth === 0 && expression.slice(index).match(pattern)?.index === 0) {
      parts.push(current);
      const match = expression.slice(index).match(pattern);
      index += match[0].length - 1;
      current = "";
      continue;
    }
    current += char;
  }
  parts.push(current);
  return parts.map((part) => part.trim()).filter(Boolean);
}

function acceptable(expression, isDirect) {
  const text = expression.trim();
  if (!text) return false;
  if (/AGPL|SSPL|Commons Clause|BUSL|Business Source|Non-?Commercial|CC-BY-NC|UNLICENSED|Proprietary/i.test(text)) {
    return false;
  }
  const orParts = splitTop(text, "OR");
  if (orParts.length > 1) return orParts.some((part) => acceptable(part, isDirect));
  const andParts = splitTop(text, "AND");
  if (andParts.length > 1) return andParts.every((part) => acceptable(part, isDirect));
  const id = canonical(text);
  const allow = isDirect ? DIRECT_ALLOW : TRANSITIVE_ALLOW;
  if (/GPL/i.test(id) && !/LGPL/i.test(id)) return false;
  return allow.has(id);
}

function licenseFile(packageDir) {
  if (!existsSync(packageDir)) return "";
  const found = readdirSync(packageDir).find((name) => /^licen[sc]e/i.test(name));
  return found ? path.join(packageDir, found) : "";
}

const packages = [];
for (const [key, entry] of Object.entries(lock.packages ?? {})) {
  if (!key) continue;
  const packageDir = path.join(root, key);
  const name = entry.name ?? key.replace(/^node_modules\//, "");
  const license = licenseOf(entry, packageDir);
  packages.push({
    name,
    version: entry.version ?? "unknown",
    license,
    direct: direct.has(name),
    licensePath: licenseFile(packageDir),
    ok: acceptable(license, direct.has(name)),
  });
}

const rejected = packages.filter((pkg) => !pkg.ok);
const byLicense = new Map();
for (const pkg of packages) {
  const key = pkg.license || "UNKNOWN";
  const list = byLicense.get(key) ?? [];
  list.push(`${pkg.name}@${pkg.version}${pkg.direct ? " (direct)" : ""}`);
  byLicense.set(key, list);
}

const directPackages = packages.filter((pkg) => pkg.direct).sort((a, b) => a.name.localeCompare(b.name));
const lines = [];
lines.push("# Third-party licenses");
lines.push("");
lines.push("Generated by `npm run licenses`. Do not hand-edit; re-run the script after dependency changes.");
lines.push("");
lines.push("Direct dependencies must use a permissive OSI license that can ship in an open-source app on Cloudflare Workers: MIT, Apache-2.0, BSD, ISC, or 0BSD. AGPL, SSPL, Commons Clause, Business Source, and non-commercial terms are rejected. Transitive packages may also use MPL-2.0, LGPL, CC0, or Unlicense. This is a project policy record, not legal advice.");
lines.push("");
lines.push("## Direct dependencies");
lines.push("");
lines.push("| Package | Version | License |");
lines.push("| --- | --- | --- |");
for (const pkg of directPackages) {
  lines.push(`| ${pkg.name} | ${pkg.version} | ${pkg.license} |`);
}
lines.push("");
lines.push("## Packages by license");
lines.push("");
for (const [license, names] of [...byLicense.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  lines.push(`### ${license}`);
  lines.push("");
  for (const name of names.sort()) lines.push(`- ${name}`);
  lines.push("");
}

const seenTexts = new Set();
lines.push("## Direct dependency license texts");
lines.push("");
for (const pkg of directPackages) {
  if (!pkg.licensePath || seenTexts.has(pkg.license)) continue;
  seenTexts.add(pkg.license);
  const text = readFileSync(pkg.licensePath, "utf8").trim();
  lines.push(`### ${pkg.license}`);
  lines.push("");
  lines.push("```");
  lines.push(text);
  lines.push("```");
  lines.push("");
}

const record = `${lines.join("\n")}\n`;
const recordPath = path.join(root, "THIRD_PARTY_LICENSES.md");
const checkOnly = process.argv.includes("--check");
if (checkOnly) {
  const current = existsSync(recordPath) ? readFileSync(recordPath, "utf8") : "";
  if (current !== record) {
    console.error("THIRD_PARTY_LICENSES.md is out of date. Run npm run licenses and commit the result.");
    process.exit(1);
  }
} else {
  writeFileSync(recordPath, record);
}

if (rejected.length > 0) {
  console.error("License policy failed:");
  for (const pkg of rejected) {
    console.error(`- ${pkg.name}@${pkg.version}: ${pkg.license || "UNKNOWN"}${pkg.direct ? " (direct)" : ""}`);
  }
  process.exit(1);
}

console.log(
  `${checkOnly ? "Checked" : "Recorded"} ${packages.length} packages (${directPackages.length} direct) in THIRD_PARTY_LICENSES.md`,
);
